static pl_node *hid_entry(uint32_t uid, const char *name, const uint8_t *descriptor, size_t len,
                          const char *display_uuid) {
    char uuid[16];
    snprintf(uuid, sizeof(uuid), "%x", (unsigned)uid);
    pl_node *d = pl_dict();
    pl_set(d, "hidProductID", pl_int(1));
    pl_set(d, "hidVendorID", pl_int(2));
    pl_set(d, "hidCountryCode", pl_int(0));
    pl_set(d, "uuid", pl_str(uuid));
    pl_set(d, "name", pl_str(name));
    pl_set(d, "displayUUID", pl_str(display_uuid));
    pl_set(d, "hidDescriptor", pl_data(descriptor, len));
    return d;
}

pl_node *hid_touch_device(int x_max, int y_max, const char *display_uuid) {
    uint8_t d[256];
    size_t n = 0;
    static const uint8_t head[] = {0x05, 0x0d, 0x09, 0x04, 0xa1, 0x01};
    memcpy(d + n, head, sizeof(head));
    n += sizeof(head);
    for (int i = 0; i < TOUCH_CONTACTS; i++) {
        const uint8_t finger[] = {
            0x05, 0x0d, 0x09, 0x22, 0xa1, 0x02,
            0x09, 0x38, 0x75, 0x08, 0x95, 0x01, 0x81, 0x02,
            0x15, 0x00, 0x25, 0x01, 0x09, 0x33, 0x75, 0x01, 0x95, 0x01, 0x81, 0x02,
            0x95, 0x07, 0x81, 0x03,
            0x05, 0x01, 0x26, (uint8_t)(x_max & 0xff), (uint8_t)((x_max >> 8) & 0xff), 0x09, 0x30,
            0x75, 0x10, 0x95, 0x01, 0x81, 0x02,
            0x26, (uint8_t)(y_max & 0xff), (uint8_t)((y_max >> 8) & 0xff), 0x09, 0x31, 0x81, 0x02, 0xc0,
        };
        memcpy(d + n, finger, sizeof(finger));
        n += sizeof(finger);
    }
    d[n++] = 0xc0;
    return hid_entry(TOUCH_HID_UID, "VitaPlay Touchscreen", d, n, display_uuid);
}

