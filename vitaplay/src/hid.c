void hid_touch_report(uint8_t out[TOUCH_CONTACTS * 6], const touch_contact contacts[TOUCH_CONTACTS]) {
    memset(out, 0, TOUCH_CONTACTS * 6);
    for (int slot = 0; slot < TOUCH_CONTACTS; slot++) {
        uint8_t *p = out + slot * 6;
        int x = contacts[slot].x < 0 ? 0 : contacts[slot].x;
        int y = contacts[slot].y < 0 ? 0 : contacts[slot].y;
        p[0] = (uint8_t)slot;
        p[1] = contacts[slot].down ? 0x01 : 0x00;
        p[2] = (uint8_t)x;
        p[3] = (uint8_t)(x >> 8);
        p[4] = (uint8_t)y;
        p[5] = (uint8_t)(y >> 8);
    }
}

static uint8_t clamp_axis(int v) { return (uint8_t)(int8_t)(v < -127 ? -127 : v > 127 ? 127 : v); }

void hid_knob_report(uint8_t out[4], const knob_state *s) {
    out[0] = (s->select ? 0x01 : 0) | (s->home ? 0x02 : 0) | (s->back ? 0x04 : 0);
    out[1] = clamp_axis(s->x);
    out[2] = clamp_axis(s->y);
    out[3] = clamp_axis(s->wheel);
}
